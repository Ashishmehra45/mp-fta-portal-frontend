"""Regenerate src/data/rooGlossary.ts from the supplied RoO glossary markdown. Usage: python3 scripts/build_roo_glossary.py <file.md>"""
import json, re, sys
sections, cur = [], None
for line in open(sys.argv[1], encoding='utf-8'):
    m = re.match(r'^## (\d+)\.\s*(.+)', line)
    if m:
        cur = {'title': m.group(2).strip(), 'terms': []} if int(m.group(1)) <= 10 else None
        if cur: sections.append(cur)
        continue
    if cur and line.startswith('|') and not re.match(r'^\|\s*-', line):
        cells = [c.strip().replace('\\&', '&') for c in line.strip().strip('|').split('|')]
        if len(cells) >= 2 and cells[0] not in ('Term', 'Abbreviation') and cells[0]:
            cur['terms'].append({'term': cells[0], 'meaning': cells[-1]})
sections = [s for s in sections if s['terms']]
out = f"""/**
 * Rules of Origin glossary. GENERATED by scripts/build_roo_glossary.py from the supplied
 * "Rules of Origin (RoO) – Complete Glossary of Terms" — regenerate, never hand-edit.
 */
export interface GlossaryTerm {{ term: string; meaning: string }}
export interface GlossarySection {{ title: string; terms: GlossaryTerm[] }}
export const rooGlossary: GlossarySection[] = {json.dumps(sections, ensure_ascii=False, indent=1)};
"""
open('src/data/rooGlossary.ts', 'w').write(out)
print([(s['title'], len(s['terms'])) for s in sections])
