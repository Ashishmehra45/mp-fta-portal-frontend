"""Regenerate src/data/productMaster.ts from the supplied product master workbook.

Usage: python3 scripts/build_product_master.py <India_Import_Export_Product_Master.xlsx>

Reads the "Base Product Reference" (product name -> HS6), "10K Search Master"
(search phrases, used to learn the generic trade words people add to a product name)
and "MP ODOP Products" (district products with search keywords and product forms) sheets.
"""
import json
import re
import sys

import pandas as pd

src = sys.argv[1]
base = pd.read_excel(src, sheet_name="Base Product Reference", dtype=str).dropna(subset=["Product Name"])
master = pd.read_excel(src, sheet_name="10K Search Master", dtype=str)
odop = pd.read_excel(src, sheet_name="MP ODOP Products", dtype=str)

words = lambda s: re.findall(r"[a-z]+", str(s).lower())
name_words = {w for n in master["Product Name"] for w in words(n)}
filler = sorted({w for k in master["Alternative Search Keyword"] for w in words(k)} - name_words)

products = []
seen = set()
for _, r in base.iterrows():
    key = (r["Product Name"].strip(), r["HS6 Reference"].strip())
    if key in seen:
        continue
    seen.add(key)
    products.append({"name": key[0], "category": r["Category"].strip(), "hs": key[1]})

groups = {}
for _, r in odop.iterrows():
    forms = [f.strip() for f in str(r["Product Forms to Search for HS Classification"]).split(";") if f.strip()]
    if any("not a goods hs code" in f.lower() for f in forms):
        continue  # services (e.g. tourism) have no goods HS code
    name = r["ODOP Product"].strip()
    g = groups.setdefault(name, {
        "name": name,
        "category": str(r["Category"]).strip(),
        "districts": [],
        "keywords": [k.strip() for k in str(r["Alternative Search Keywords"]).split(",") if k.strip()],
        "forms": forms,
    })
    if r["ODOP District"].strip() not in g["districts"]:
        g["districts"].append(r["ODOP District"].strip())

out = f"""/**
 * Product master for product / HS code search suggestions.
 * GENERATED by scripts/build_product_master.py from the supplied workbook
 * "India_Import_Export_Product_Master_10000_1.xlsx" — regenerate, never hand-edit.
 *
 * HS6 references are preliminary lookup aids, not a final customs classification
 * (per the workbook's Read Me). MP ODOP products carry no HS code in the workbook,
 * so they suggest product forms to search for instead.
 */

export interface MasterProduct {{
  name: string;
  category: string;
  /** HS6 reference (some rows are 4-digit headings) */
  hs: string;
}}

export interface MasterOdopProduct {{
  name: string;
  category: string;
  districts: string[];
  keywords: string[];
  /** Product forms to search for when classifying */
  forms: string[];
}}

export const PRODUCT_MASTER_SOURCE = 'India Import Export Product Master (10,000 search rows)';

/** Generic trade words people add to a product name ("buy", "supplier", "export"…), ignored when searching. */
export const TRADE_FILLER_WORDS: string[] = {json.dumps(filler)};

export const masterProducts: MasterProduct[] = {json.dumps(products, ensure_ascii=False, indent=1)};

export const masterOdopProducts: MasterOdopProduct[] = {json.dumps(list(groups.values()), ensure_ascii=False, indent=1)};
"""
open("src/data/productMaster.ts", "w").write(out)
print(len(products), "products,", len(groups), "ODOP products,", len(filler), "filler words")
